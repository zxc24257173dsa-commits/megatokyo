"""Read CSV / XLSX into plain sheets of cell values.

* XLSX: every worksheet is read (read-only mode). Values are the ones Excel last calculated.
  A formula cell that was never calculated (file generated by a script and never opened in
  Excel) is returned as UNCALCULATED so validation can say so instead of treating it as empty.
* CSV: encoding detected among UTF-8 (with/without BOM), Shift_JIS/CP932 (Japanese Excel)
  and Big5 (Traditional Chinese Excel); delimiter sniffed (comma, semicolon, tab).
* XML parsing is protected by defusedxml (installed, picked up by openpyxl automatically).
"""
import csv
import io
from dataclasses import dataclass, field
from zipfile import BadZipFile

import openpyxl

from app.core.errors import AppError

MAX_ROWS_PER_SHEET = 20_000
MAX_COLUMNS = 200


class _Uncalculated:
    def __repr__(self) -> str:
        return "UNCALCULATED"


UNCALCULATED = _Uncalculated()


@dataclass
class Sheet:
    name: str
    rows: list[list] = field(default_factory=list)


def read(filename: str, data: bytes) -> list[Sheet]:
    name = filename.lower()
    if name.endswith((".xlsx", ".xlsm")) or data[:2] == b"PK":
        return _read_xlsx(data)
    if name.endswith((".csv", ".tsv", ".txt")):
        return [_read_csv(data)]
    if name.endswith(".xls"):
        raise AppError("unsupported_file_type", "Old .xls format: please save as .xlsx or CSV in Excel", 415)
    raise AppError("unsupported_file_type", "Only .xlsx and .csv files are supported", 415)


def _trim(rows: list[list]) -> list[list]:
    """Drop trailing empty cells / rows (Excel often reports thousands of blank rows)."""
    out = []
    for r in rows:
        r = list(r[:MAX_COLUMNS])
        while r and (r[-1] is None or r[-1] == ""):
            r.pop()
        out.append(r)
    while out and not out[-1]:
        out.pop()
    if len(out) > MAX_ROWS_PER_SHEET:
        raise AppError("too_many_rows", f"A sheet may have at most {MAX_ROWS_PER_SHEET} rows", 413)
    return out


def _read_xlsx(data: bytes) -> list[Sheet]:
    try:
        values_wb = openpyxl.load_workbook(io.BytesIO(data), read_only=True, data_only=True)
        formulas_wb = openpyxl.load_workbook(io.BytesIO(data), read_only=True, data_only=False)
    except (BadZipFile, KeyError, OSError, ValueError) as exc:
        raise AppError("unreadable_file", "The Excel file could not be read (damaged or not .xlsx)", 422) from exc
    sheets = []
    try:
        for ws_v in values_wb.worksheets:
            ws_f = formulas_wb[ws_v.title]
            rows = []
            for i, (rv, rf) in enumerate(zip(ws_v.iter_rows(values_only=True), ws_f.iter_rows(values_only=True))):
                if i >= MAX_ROWS_PER_SHEET + 1000:
                    break
                row = []
                for v, f in zip(rv, rf):
                    if v is None and isinstance(f, str) and f.startswith("="):
                        row.append(UNCALCULATED)
                    else:
                        row.append(v)
                rows.append(row)
            sheets.append(Sheet(ws_v.title, _trim(rows)))
    finally:
        values_wb.close()
        formulas_wb.close()
    return sheets


def _decode(data: bytes) -> str:
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return data.decode("utf-16")
    for enc in ("utf-8-sig", "cp932", "big5"):
        try:
            return data.decode(enc)
        except UnicodeDecodeError:
            continue
    raise AppError("unreadable_file", "Could not detect the CSV text encoding; save it as UTF-8", 422)


def _read_csv(data: bytes) -> Sheet:
    text = _decode(data)
    try:
        dialect = csv.Sniffer().sniff(text[:5000], delimiters=",;\t")
    except csv.Error:
        dialect = csv.excel
    rows = [list(r) for r in csv.reader(io.StringIO(text), dialect)]
    return Sheet("CSV", _trim([[c if c != "" else None for c in r] for r in rows]))
